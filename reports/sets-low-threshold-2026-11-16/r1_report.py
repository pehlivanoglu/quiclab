"""Tables and timelines for R1 (rows.jsonl from r1.py). Aggregation as grouping_score.pooled: leaf P / R / F1 =
mean over runs of the per-run close means; pair P / R from the summed pair counts; spurious = mean over runs."""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

PASS_PP = 0.93          # pre-set condition (user)
KF_S = 0.2              # (T) keyframe-aligned (phase): event t0 within 200 ms after a GOP boundary (uniform: 20 %)
FQ = ("fq_codel", "cake")
LEVELS = ("T100", "T75", "T50", "T25")


def load(path: Path) -> list[dict]:
    rows = [json.loads(x) for x in path.read_text().splitlines() if x.strip()]
    bad = [r for r in rows if "error" in r]
    return [r for r in rows if "error" not in r], bad


def variants():
    """(label, method key, level)"""
    out = [("V0 (frozen, T100)", "V", "T100")]
    out += [(f"V1 {lv}", "V", lv) for lv in LEVELS[1:]]
    out += [(f"V2 {lv}", "V2", lv) for lv in LEVELS[1:]]
    return out


def f_(x, d=2):
    return "-" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"


def single(r):
    return not r["calm"] and r["aqm"] not in FQ


def fqcell(r):
    return not r["calm"] and r["aqm"] in FQ


def pooled_vals(R, sel, meth, lv, k, rep):
    ss = [r["methods"][f"{meth} k{k}"] for r in R if r["level"] == lv and r["rep"] == rep and sel(r)]
    if not ss:
        return {}
    xs = lambda i: [s["levels"]["leaf"][i] for s in ss if "leaf" in s["levels"]]   # noqa: E731
    p = np.sum([s["pairs"] for s in ss], axis=0)
    return {"P": float(np.mean(xs(0))), "R": float(np.mean(xs(1))), "F": float(np.mean(xs(2))),
            "pP": p[0] / (p[0] + p[1]) if p[0] + p[1] else None, "pR": p[0] / (p[0] + p[2]) if p[0] + p[2] else None,
            "sp": float(np.mean([s["spur"] for s in ss]))}


def times(R, sel, meth, lv, k, rep):
    """(events, run-clock s, s since the leaf's first own stimulus, never, leaves) over leaves."""
    ev, sec, since, never, n = [], [], [], 0, 0
    for r in R:
        if r["level"] != lv or r["rep"] != rep or not sel(r):
            continue
        s = r["methods"][f"{meth} k{k}"]
        for name, info in r["truth"].items():
            if info["level"] != "leaf":
                continue
            n += 1
            if name in s["t_ok"]:
                e, t = s["t_ok"][name]
                ev.append(e)
                sec.append(t)
                fs = r["first_stim"].get(name)
                if fs is not None:
                    since.append(t - fs)
            else:
                never += 1
    q = lambda v, p: float(np.percentile(v, p)) if v else None   # noqa: E731
    return {"ev50": q(ev, 50), "ev90": q(ev, 90), "s50": q(sec, 50), "s90": q(sec, 90), "f50": q(since, 50),
            "f90": q(since, 90), "never": never, "n": n}


def report(path: Path) -> None:
    R, bad = load(path)
    P = print
    P("# R1 tables (generated by r1_report.py)\n")
    if bad:
        P(f"Runs with errors: {[b['run'] for b in bad]}\n")
    nruns = {lv: len({r['run'] for r in R if r['level'] == lv}) for lv in LEVELS}
    P(f"Runs per level: {nruns}. Single-queue cells: {len({r['run'] for r in R if single(r)})}, "
      f"fq_codel cells: {len({r['run'] for r in R if fqcell(r)})}, calm runs: {len({r['run'] for r in R if r['calm']})}.\n")

    P("## 1. Pre-set condition: pair precision >= 0.93 in both reps at k = 2 and k = 3 (single-queue cells)\n")
    P("| variant | pair P k2 (r1 / r2) | pair P k3 (r1 / r2) | result |\n|---|---|---|---|")
    for lab, meth, lv in variants():
        vals = {k: [pooled_vals(R, single, meth, lv, k, rep).get("pP") for rep in (1, 2)] for k in (2, 3)}
        ok = all(x is not None and x >= PASS_PP for k in (2, 3) for x in vals[k])
        mixed = any((vals[k][0] is not None and vals[k][1] is not None) and
                    ((vals[k][0] >= PASS_PP) != (vals[k][1] >= PASS_PP)) for k in (2, 3))
        P(f"| {lab} | {f_(vals[2][0], 3)} / {f_(vals[2][1], 3)} | {f_(vals[3][0], 3)} / {f_(vals[3][1], 3)} | "
          f"{'PASS' if ok else 'FAIL'}{' (reps disagree: not reliable)' if mixed else ''} |")
    P()

    P("## 2. Time to the first correct leaf group (F1 >= 0.9), single-queue cells, r1 / r2\n")
    P("Run clock = the close's time in the run (as the frozen scorer reports it; includes the time before the leaf's "
      "first stimulus). Since first stimulus = close time minus the start of the first stimulus window targeting "
      "that leaf.\n")
    P("| variant | k | events p50 | events p90 | run clock s p50 | p90 | since first stimulus s p50 | p90 | never / leaves |")
    P("|---|---|---|---|---|---|---|---|---|")
    for lab, meth, lv in variants():
        for k in (2, 3):
            t = [times(R, single, meth, lv, k, rep) for rep in (1, 2)]
            P(f"| {lab} | {k} | " + " | ".join(" / ".join(f_(x[key], 0) for x in t) for key in
                                              ("ev50", "ev90", "s50", "s90", "f50", "f90")) +
              f" | {t[0]['never']}/{t[0]['n']} ; {t[1]['never']}/{t[1]['n']} |")
    P()

    P("## 3. Calm runs (no stimulus): groups at the end of the run\n")
    P("Kinds against the topology: leaf = all members behind one leaf egress; upstream = behind one shared "
      "non-leaf egress but not one leaf; coincidence = neither.\n")
    P("| level | runs | events / flow-minute | k2 V groups (leaf / upstream / coincidence) | k3 V | k2 V2 | k3 V2 |")
    P("|---|---|---|---|---|---|---|")
    for lv in LEVELS:
        cs = [r for r in R if r["calm"] and r["level"] == lv]
        fm = sum(r["n_clients"] * r["duration"] / 60 for r in cs)
        ne = sum(len(r["events"]) for r in cs)
        cells = []
        for key in ("V k2", "V k3", "V2 k2", "V2 k3"):
            c = Counter(g["kind"] for r in cs for g in r.get("final", {}).get(key, []))
            cells.append(f"{c['leaf']} / {c['upstream']} / {c['coincidence']}" if lv != "T100" or key.startswith("V ")
                         else "-")
        P(f"| {lv} | {len(cs)} | {f_(ne / fm if fm else None, 3)} | " + " | ".join(cells) + " |")
    P()
    by = defaultdict(list)
    for r in R:
        if r["calm"] and r["level"] in ("T50", "T25"):
            gs = [g for g in r.get("final", {}).get("V k2", [])]
            if gs:
                by[r["level"]].append(f"{r['run']}: " + "; ".join(f"{{{','.join(g['members'])}}} x{g['support']} "
                                                                    f"({g['kind']})" for g in gs))
    for lv, lines in by.items():
        P(f"Calm groups at {lv}, V k2:\n")
        for x in lines[:20]:
            P(f"- {x}")
        P()

    P("## 4. Events per flow-minute and where they come from (stimulus runs)\n")
    P("in window = t0 within [start - 1 s, end + 2 s] of a truth stimulus window; keyframe = most members' onsets "
      "within one tick (33 ms) of a GOP boundary; other = neither. Sets of >= 2 members: one leaf / upstream / "
      "coincidence.\n")
    P("Keyframe columns: (one tick) the brief's rule on the members' onsets; (phase) event t0 within 200 ms after a GOP "
      "boundary (T) — the score's keyframe peaks come 50-150 ms after the boundary, so the one-tick rule undercounts. "
      "Phase shares are of the events in / outside the windows; a uniform phase gives 0.20.\n")
    P("| level | events / flow-minute | in window | keyframe, one tick (outside windows) | other | phase < 200 ms: in window | phase: outside | single-member | leaf | upstream | coincidence | strong (V2) |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for lv in LEVELS:
        rs = [r for r in R if not r["calm"] and r["level"] == lv]
        fm = sum(r["n_clients"] * r["duration"] / 60 for r in rs)
        ev = [e for r in rs for e in r["events"]]
        n = len(ev) or 1
        inw = sum(e["in_window"] for e in ev)
        key = sum(e["key"] and not e["in_window"] for e in ev)
        sets = Counter(e["set"] for e in ev)
        multi = sum(v for k_, v in sets.items() if k_ != "single") or 1
        ph_in = [e["t0"] % 1.0 < KF_S for e in ev if e["in_window"]]
        ph_out = [e["t0"] % 1.0 < KF_S for e in ev if not e["in_window"]]
        P(f"| {lv} | {f_(len(ev) / fm if fm else None, 3)} | {inw / n:.2f} | {key / n:.2f} | {(n - inw - key) / n:.2f} | "
          f"{f_(float(np.mean(ph_in)) if ph_in else None)} | {f_(float(np.mean(ph_out)) if ph_out else None)} | "
          f"{sets['single'] / n:.2f} | {sets['leaf'] / multi:.2f} | {sets['upstream'] / multi:.2f} | "
          f"{sets['coincidence'] / multi:.2f} | {sum(e['strong'] for e in ev) / n:.2f} |")
    P()

    P("## 5. Common scorer, single-queue cells (r1 / r2)\n")
    table(R, single)
    P("## 6. Missed members by cause (clients behind a hot leaf egress not in the event), stimulus runs\n")
    P("| level | missed members | split event | already in alarm | other | per event with a hot leaf |")
    P("|---|---|---|---|---|---|")
    for lv in LEVELS:
        ev = [e for r in R if not r["calm"] and r["level"] == lv for e in r["events"]]
        miss = Counter(m for e in ev for m in e["missed"])
        n = sum(miss.values()) or 1
        hot_ev = sum(1 for e in ev if e["missed"] or e["set"] != "single") or 1
        P(f"| {lv} | {sum(miss.values())} | {miss['split event'] / n:.2f} | {miss['already in alarm'] / n:.2f} | "
          f"{miss['other'] / n:.2f} | {sum(miss.values()) / hot_ev:.2f} |")
    P()
    P("## 7. fq_codel cells, same-link truth (r1 / r2)\n")
    table(R, fqcell)
    P("## 8. Late joiner (V, frozen SETS replay), single-queue cells\n")
    P("| level | k | joined / cases | events p50 | seconds p50 |\n|---|---|---|---|---|")
    for lv in LEVELS:
        for k in (2, 3):
            lj = [x for r in R if r["level"] == lv and single(r) for x in r["late"] if x["method"] == f"V k{k}"]
            j = [x for x in lj if x["joined"]]
            P(f"| {lv} | {k} | {len(j)}/{len(lj)} | {f_(float(np.median([x['events'] for x in j])) if j else None, 0)} | "
              f"{f_(float(np.median([x['seconds'] for x in j])) if j else None, 0)} |")
    P()
    P("## 9. Distinct sets in the table at the end of the run (mean over runs)\n")
    P("| level | single-queue | fq_codel | calm |\n|---|---|---|---|")
    for lv in LEVELS:
        m = lambda sel: f_(float(np.mean([r.get("n_sets", 0) for r in R if r["level"] == lv and sel(r)])), 1)  # noqa: E731
        P(f"| {lv} | {m(single)} | {m(fqcell)} | {m(lambda r: r['calm'])} |")
    P()


def table(R, sel):
    print("| variant | k | leaf P | leaf R | leaf F1 | pair P | pair R | spurious / close |")
    print("|---|---|---|---|---|---|---|---|")
    for lab, meth, lv in variants():
        for k in (2, 3):
            v = [pooled_vals(R, sel, meth, lv, k, rep) for rep in (1, 2)]
            print(f"| {lab} | {k} | " + " | ".join(" / ".join(f_(x.get(key)) for x in v) for key in
                                                  ("P", "R", "F", "pP", "pR", "sp")) + " |")
    print()


def plots(path: Path) -> None:
    """Pick one helpful weak event, one keyframe-aligned event and one coincidence event and draw their timelines."""
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import det_eval as d
    import shadow_v2_frozen as fz
    import shadow_v2_step3 as s3
    R, _ = load(path)
    here = Path(__file__).resolve().parent
    kdir = Path(__file__).resolve().parents[2] / ".runs" / "2026-11-14_1818_v3"

    def pick(cond, lv="T50"):
        for r in R:
            if r["level"] != lv or r["calm"] or r["aqm"] in FQ:
                continue
            for e in r["events"]:
                if cond(r, e):
                    return r, e
        return None, None
    picks = {
        "helpful-weak": pick(lambda r, e: not e["strong"] and e["in_window"] and e["set"] == "leaf" and e["n"] >= 2
                             and 0.25 <= e["t0"] % 1.0 <= 0.9),
        "keyframe": pick(lambda r, e: e["t0"] % 1.0 < KF_S and not e["in_window"] and e["n"] >= 3),
        "coincidence": pick(lambda r, e: e["set"] == "coincidence" and not e["in_window"]),
    }
    for name, (r, e) in picks.items():
        if r is None:
            print(f"{name}: no example found")
            continue
        run = d.Run(kdir / r["run"])
        fit = fz.FROZEN["OWD"]
        s3.FLOORS.clear()
        s3.FLOORS.update(fit["floors"])
        s3.FIXED_STATS.clear()
        s3.FIXED_STATS.update(fit["stats"])
        label = fz.LABEL["v2"] + " +hold gate:level+cap"
        files = fz.tick_files(run, "OWD")
        wins = json.loads((kdir / r["run"] / "grouping" / "windows.json").read_text())
        lo, hi = e["t0"] - 6, e["t0"] + 6
        fig, ax = plt.subplots(figsize=(10, 4.5))
        for s, f in sorted(files.items()):
            if s == "sub-ctrl":
                continue
            res = s3.run_cusum(s3.load_flow(f), label, fit["g_ref"]["v2"], False)
            t = np.asarray(res["t"])
            m = (t >= lo) & (t <= hi)
            ax.plot(t[m], np.asarray(res["score"])[m], lw=1, label=s)
        for th, ls in ((0.25, "-"), (0.125, "--"), (0.0625, ":")):
            ax.axhline(th, color="k", lw=0.7, ls=ls)
        for w in wins:
            if w["end"] >= lo and w["start"] <= hi:
                ax.axvspan(max(lo, w["start"]), min(hi, w["end"]), color="orange", alpha=0.15)
        for x in np.arange(np.ceil(lo), hi, 1.0):
            ax.axvline(x, color="grey", lw=0.4, alpha=0.5)
        ax.axvline(e["t0"], color="red", lw=1)
        ax.set_xlim(lo, hi)
        ax.set_xlabel("run time (s); grey lines: GOP boundaries; orange: stimulus windows; red: event t0")
        ax.set_ylabel("congestion score")
        ax.set_title(f"{name}: {r['run']} T50 event at {e['t0']} s ({e['n']} members, set {e['set']}, "
                     f"{'strong' if e['strong'] else 'weak'})", fontsize=9)
        ax.legend(fontsize=7, ncol=4)
        fig.tight_layout()
        fig.savefig(here / f"timeline-{name}.png", dpi=110)
        plt.close(fig)
        print(f"{name}: {r['run']} t0 {e['t0']}")
